"""Agent-format SFT of the student on the 27B teacher's strict-correct transcripts (arm A2: learn from the 27B,
then RL). Data: scripts/build_sft_27b.py -> data/sft_27b/{train,val}.jsonl.

Rendering is the student's own chat template (Qwen3.5 "think" template, identical to TRL's qwen3_5_think.jinja)
with enable_thinking=False and tools=[smolenv_local.BASH_TOOL]: the exact text vLLM builds for every model call in
the eval harness. The template has no {% generation %} markers, so TRL's assistant_only_loss would swap in TRL's
qwen3_5_think_training.jinja, which puts the empty "<think>\\n\\n</think>\\n\\n" block (part of the thinking-off
generation prompt, never generated by the model) and the "\\n" after <|im_end|> inside the loss. Instead the mask
is built here by incremental rendering and passed to TRL as a pre-tokenized `labels` column:

    for each assistant message i:
        ctx  = render(messages[:i],   add_generation_prompt=True)   # what vLLM feeds the model for call i
        upto = render(messages[:i+1])                                # what vLLM feeds it for every later call
        assert upto startswith ctx and full startswith upto          # no template drift between turns
        loss on upto[len(ctx) : last <|im_end|>]                     # content + <tool_call> XML + <|im_end|>

Only those tokens carry loss: system, user, tool responses, the assistant header, the empty think block, and the
"\\n" after <|im_end|> are -100. Assistant turns listed in `no_loss_msgs` (teacher calls cut off at its 1,024-token
limit, rendered as a tool call with no arguments) stay in the context but carry no loss.

    # no GPU, no weights: render N real examples, print token counts, the masked/trained spans, the
    # incremental-render proof, and a comparison with the token sequence TRL 1.14 GRPO builds in RL
    python train_sft_agent.py --dry-run --dry-n 3

    # Spark, inside smol-train:v2 (GPU)
    python train_sft_agent.py --out runs/sft-27b-m1-lora
"""
