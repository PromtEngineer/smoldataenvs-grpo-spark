GEN_PROMPT_TAIL = "<|im_start|>assistant\n<think>\n\n</think>\n\n"  # thinking-off generation prompt of this template


class TemplateDrift(AssertionError):
    """The chat template renders a conversation prefix differently depending on what follows it."""


# ── rendering and loss mask (no torch; shared with scripts/build_sft_27b.py) ─────────────────────────────────────

def template_sha(tok) -> str:
    return hashlib.sha256((tok.chat_template or "").encode()).hexdigest()[:16]


def render(tok, messages: list[dict], tools: list[dict], add_generation_prompt: bool) -> tuple[str, list[int]]:
    """Render with the tokenizer's chat template and tokenize the text, as vLLM does (add_special_tokens=False)."""
    text = tok.apply_chat_template(messages, tools=tools, tokenize=False, add_generation_prompt=add_generation_prompt,
                                   **TEMPLATE_KWARGS)
    return text, tok(text, add_special_tokens=False)["input_ids"]


def render_and_mask(tok, messages: list[dict], tools: list[dict], no_loss_msgs=()) -> dict:
    """Token ids of the full conversation, labels (-100 except on assistant-generated tokens), and per-turn spans.

    Raises TemplateDrift if any assistant turn's generation-time context is not a token-level prefix of the full
    render, which would mean the model was trained on a context it never sees at inference."""
    eos = tok.eos_token_id  # <|im_end|>
    im_start = tok.convert_tokens_to_ids("<|im_start|>")
    full_text, full = render(tok, messages, tools, False)
    labels = [-100] * len(full)
    turns = []
    no_loss = set(no_loss_msgs)
    for i, m in enumerate(messages):
        if m["role"] != "assistant":
            continue
        ctx_text, ctx = render(tok, messages[:i], tools, True)
        _, upto = render(tok, messages[: i + 1], tools, False)
        if not ctx_text.endswith(GEN_PROMPT_TAIL):
            raise TemplateDrift(f"msg {i}: generation prompt does not end with {GEN_PROMPT_TAIL!r}")
        if upto[: len(ctx)] != ctx:
            raise TemplateDrift(f"msg {i}: render(prefix, add_generation_prompt=True) is not a prefix of the turn")
        if full[: len(upto)] != upto:
            raise TemplateDrift(f"msg {i}: the rendered turn is not a prefix of the full conversation")
        end = len(upto) - 1
        while end >= len(ctx) and upto[end] != eos:
            end -= 1
        if end < len(ctx) or tok.decode(upto[end + 1:]) != "\n":
            raise TemplateDrift(f"msg {i}: assistant turn does not close with <|im_end|>\\n")
        span = full[len(ctx): end + 1]
        if im_start in span:
            raise TemplateDrift(f"msg {i}: assistant span contains <|im_start|>")
        trained = i not in no_loss
        if trained:
            labels[len(ctx): end + 1] = span
        turns.append({"msg": i, "start": len(ctx), "end": end + 1, "n": end + 1 - len(ctx), "trained": trained})
    return {"input_ids": full, "labels": labels, "turns": turns, "text": full_text}


_TOK = None


def _worker_init(tok_path: str) -> None:
    global _TOK
    from transformers import AutoTokenizer

    _TOK = AutoTokenizer.from_pretrained(tok_path)


def _encode_row(row: dict) -> dict:
    try:
        enc = render_and_mask(_TOK, row["messages"], row["tools"], row.get("no_loss_msgs", ()))
    except TemplateDrift as e:  # reported and dropped by the caller, never trained on
        return {"task_id": row["task_id"], "error": str(e)}
    return {"task_id": row["task_id"], "input_ids": enc["input_ids"], "labels": enc["labels"],
            "turn_lengths": [t["n"] for t in enc["turns"]]}


def encode_rows(rows: list[dict], tok_path: str, workers: int = 8) -> list[dict]:
    """render_and_mask over many rows in worker processes (each loads its own tokenizer)."""
    if workers <= 1:
        _worker_init(tok_path)
        return [_encode_row(r) for r in rows]
    import multiprocessing as mp

    with mp.get_context("fork").Pool(workers, initializer=_worker_init, initargs=(tok_path,)) as pool:
        return pool.map(_encode_row, rows, chunksize=8)


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(l) for l in path.read_text().splitlines() if l.strip()]


# ── dry run: the proof ────────────────────────────────────────────────────────────────────────────────────────────

def _clip(s: str, head: int, tail: int) -> str:
    return s if len(s) <= head + tail + 20 else f"{s[:head]} [... {len(s) - head - tail} chars ...] {s[-tail:]}"


def _show(s: str) -> str:
    return s.replace("\n", "\\n\n")  # make every newline visible and keep line breaks


def span_visual(tok, ids: list[int], labels: list[int], head: int = 160, tail: int = 80) -> str:
    """Contiguous runs of masked / trained tokens, decoded. Trained runs are shown in full."""
    out, i = [], 0
    while i < len(ids):
        j, trained = i, labels[i] != -100
        while j < len(ids) and (labels[j] != -100) == trained:
            j += 1
        text = tok.decode(ids[i:j])
        if trained:
            out.append(f"  ▶▶ LOSS  tokens [{i}:{j}) n={j - i}\n{_show(text)}\n  ◀◀ end LOSS")
        else:
            out.append(f"  ·· masked tokens [{i}:{j}) n={j - i}: {_clip(text, head, tail)!r}")
        i = j
    return "\n".join(out)


def rl_sequence(proc, tokenizer, messages: list[dict], enc: dict, rl_tools: list) -> tuple[list[int], list[int]]:
    """Token ids and loss mask the way TRL 1.14 GRPOTrainer(environment_factory=...) assembles one episode:
    prompt = processor.apply_chat_template([system, user], tools=env tools, add_generation_prompt=True),
    then per model call its generated ids (here: the teacher turn's canonical tokens, content ... <|im_end|>, mask 1)
    and after each tool round GRPOTrainer._get_tool_suffix_ids(tool messages) (mask 0)."""
    from types import SimpleNamespace

    from trl.data_utils import prepare_multimodal_messages
    from trl.trainer.grpo_trainer import GRPOTrainer

    prompt = prepare_multimodal_messages([dict(m) for m in messages[:2]])
    ids = list(proc.apply_chat_template(conversation=[prompt], tools=rl_tools, chat_template=None,
                                        add_generation_prompt=True, tokenize=True, return_dict=True,
                                        **TEMPLATE_KWARGS)["input_ids"][0])
    mask = [0] * len(ids)
    fake = SimpleNamespace(processing_class=proc, chat_template=None, chat_template_kwargs=dict(TEMPLATE_KWARGS),
                           _is_vlm=True, _tokenizer=tokenizer)
    turn_by_msg = {t["msg"]: t for t in enc["turns"]}
    i = 2
    while i < len(messages):
        t = turn_by_msg[i]
        gen = enc["input_ids"][t["start"]: t["end"]]
        ids += gen
        mask += [1] * len(gen)
        i += 1
        tool_msgs = []
        while i < len(messages) and messages[i]["role"] == "tool":
            tool_msgs.append({"role": "tool", "name": messages[i]["name"], "content": messages[i]["content"]})
            i += 1
        if tool_msgs:
            suffix = GRPOTrainer._get_tool_suffix_ids(fake, tool_msgs)
            ids += suffix
            mask += [0] * len(suffix)
    return ids, mask


def compare_rl(tok, full: list[int], labels: list[int], rl_ids: list[int], rl_mask: list[int],
               no_loss_spans=()) -> str:
    sft = full[:-1] if tok.decode(full[-1:]) == "\n" else full  # RL episodes end at the final <|im_end|>
    sft_mask = [int(l != -100) for l in labels[: len(sft)]]
    if rl_ids == sft:
        diff = [n for n, (x, y) in enumerate(zip(rl_mask, sft_mask)) if x != y]
        by_design = sum(e - s for s, e in no_loss_spans)
        if diff and all(any(s <= n < e for s, e in no_loss_spans) for n in diff) and len(diff) == by_design:
            return (f"IDENTICAL: {len(sft)} tokens; loss masks equal except the {len(diff)} tokens of no_loss_msgs "
                    f"turns (RL trains every generated token; SFT skips the malformed teacher call by design)")
        return f"IDENTICAL: {len(sft)} tokens, loss masks equal: {not diff}"
    k = next((n for n, (x, y) in enumerate(zip(rl_ids, sft)) if x != y), min(len(rl_ids), len(sft)))
    # re-align after the first difference: find the longest common suffix
    s = 0
    while s < min(len(rl_ids), len(sft)) - k and rl_ids[-1 - s] == sft[-1 - s]:
        s += 1
    msg = (f"DIFFER: RL {len(rl_ids)} vs SFT {len(sft)} tokens; first difference at token {k}; the last {s} tokens "
           f"are identical; differing region RL[{k}:{len(rl_ids) - s}] vs SFT[{k}:{len(sft) - s}]\n"
           f"      RL : {_clip(tok.decode(rl_ids[k:len(rl_ids) - s]), 220, 120)!r}\n"
           f"      SFT: {_clip(tok.decode(sft[k:len(sft) - s]), 220, 120)!r}")
    off = len(rl_ids) - len(sft)  # RL position = SFT position + off, inside the identical tail
    diff = [n for n in range(len(sft) - s, len(sft)) if rl_mask[n + off] != sft_mask[n]]
    if not diff:
        return msg + f"\n      loss masks over the identical {s}-token tail: equal"
    if all(any(a <= n < b for a, b in no_loss_spans) for n in diff):
        return msg + (f"\n      loss masks over the identical {s}-token tail: equal except the {len(diff)} tokens of "
                      f"no_loss_msgs turns (by design)")
    return msg + f"\n      loss masks over the identical {s}-token tail: {len(diff)} positions differ"


def check_rl_completions(tok, pattern: str, limit: int = 0) -> None:
    """Are the student's own RL generations in the canonical format the SFT targets use? The logged completions are
    decoded without special tokens, so assistant segments are split on the tool-response boundaries."""
    import glob
    import re

    import pandas as pd

    files = sorted(glob.glob(pattern))
    if not files:
        print(f"  (no logged RL completions at {pattern})")
        return
    boundary = re.compile(r"\nuser(?:\n<tool_response>\n.*?\n</tool_response>)+\nassistant\n<think>\n\n</think>\n\n",
                          re.S)
    call_re = re.compile(r"<tool_call>\n<function=([^\n>]+)>\n((?:<parameter=[^>\n]+>\n.*?\n</parameter>\n)*)"
                         r"</function>\n</tool_call>", re.S)
    param_re = re.compile(r"<parameter=([^>\n]+)>\n(.*?)\n</parameter>\n", re.S)
    n_seg = n_ok = n_trunc = n_ws = 0
    bad = []
    for f in files[: limit or None]:
        for comp in pd.read_parquet(f, columns=["completion"])["completion"]:
            segs = boundary.split(comp)
            for si, seg in enumerate(segs):
                is_last = si == len(segs) - 1
                n_seg += 1
                calls = list(call_re.finditer(seg))
                content = seg[: calls[0].start()] if calls else seg
                msg = {"role": "assistant", "content": content.strip()}
                if calls:
                    msg["tool_calls"] = [{"type": "function", "function": {
                        "name": c.group(1), "arguments": dict(param_re.findall(c.group(2)))}} for c in calls]
                text, _ = render(tok, [{"role": "user", "content": "q"}, msg], None, False)
                body = text.split(GEN_PROMPT_TAIL, 1)[1].removesuffix("<|im_end|>\n")
                if body == seg:
                    n_ok += 1
                elif is_last and "<tool_call>" in seg and not seg.rstrip().endswith("</tool_call>"):
                    n_trunc += 1  # cut by max_completion_length inside a tool call
                elif is_last and not calls and seg.rstrip() == body:
                    n_ws += 1  # final text segment whose only difference is trailing whitespace the template trims
                else:
                    bad.append((f, seg, body))
    print(f"  {n_seg} assistant segments from {len(files)} files: {n_ok} re-render byte-identically; "
          f"{n_trunc} are final segments cut inside a tool call by the completion budget; {n_ws} are final text "
          f"segments that differ only by trailing whitespace; {len(bad)} differ otherwise")
    for f, seg, body in bad[:3]:
        print(f"    e.g. {Path(f).name}: generated {_clip(seg, 150, 100)!r}\n"
              f"         canonical {_clip(body, 150, 100)!r}")


